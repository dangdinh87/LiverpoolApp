/**
 * Rebuilds every static copy of the mark from MARK in src/lib/brand.ts:
 *   public/brand/icon.svg, favicon-32.png, icon-192.png, icon-512.png,
 *   apple-touch-icon.png, icon-maskable-512.png and src/app/favicon.ico.
 *
 *   npx tsx scripts/build-brand-icons.ts
 *
 * Rounded tiles for the browser and the "any" icons. iOS rounds the touch icon
 * itself (transparent corners would turn black), so that one is a full square;
 * the maskable icon is full-bleed with the art shrunk into the safe zone.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "playwright";
import { BRAND, MARK } from "../src/lib/brand";

const ROOT = join(__dirname, "..");
const BRAND_DIR = join(ROOT, "public/brand");

function markSvg({ rounded = true, scale = 1, title = false } = {}): string {
  const { size, radius, back, front, backFill, rule } = MARK;
  const c = size / 2;
  const art = [
    `<polygon points="${back}" fill="${backFill}"/>`,
    `<polygon points="${front}" fill="#ffffff"/>`,
    `<rect x="${rule.x}" y="${rule.y}" width="${rule.width}" height="${rule.height}" fill="${BRAND.gold}"/>`,
  ].join("\n  ");
  const group = scale === 1 ? art : `<g transform="translate(${c} ${c}) scale(${scale}) translate(${-c} ${-c})">\n  ${art}\n  </g>`;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}"${title ? ` role="img" aria-label="${BRAND.name}"` : ""}>`,
    title ? `  <title>${BRAND.name}</title>\n  <!-- Generated by scripts/build-brand-icons.ts from MARK in src/lib/brand.ts. -->` : "",
    `  <rect width="${size}" height="${size}"${rounded ? ` rx="${radius}"` : ""} fill="${BRAND.red}"/>`,
    `  ${group}`,
    `</svg>`,
    "",
  ]
    .filter(Boolean)
    .join("\n");
}

/** A .ico holding PNG images (Vista+ format): a 6-byte header, a 16-byte entry per image, then the images. */
function packIco(pngs: { size: number; data: Buffer }[]): Buffer {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  let offset = 6 + 16 * pngs.length;
  const entries = pngs.map(({ size, data }) => {
    const e = Buffer.alloc(16);
    e.writeUInt8(size >= 256 ? 0 : size, 0);
    e.writeUInt8(size >= 256 ? 0 : size, 1);
    e.writeUInt16LE(1, 4); // colour planes
    e.writeUInt16LE(32, 6); // bits per pixel
    e.writeUInt32LE(data.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += data.length;
    return e;
  });
  return Buffer.concat([header, ...entries, ...pngs.map((p) => p.data)]);
}

async function main() {
  writeFileSync(join(BRAND_DIR, "icon.svg"), markSvg({ title: true }));

  const browser = await chromium.launch();
  const render = async (svg: string, px: number, transparent: boolean) => {
    const page = await browser.newPage({ viewport: { width: px, height: px }, deviceScaleFactor: 1 });
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg.replace(/width="\d+" height="\d+"/, `width="${px}" height="${px}"`)}</body></html>`);
    const png = await page.screenshot({ clip: { x: 0, y: 0, width: px, height: px }, omitBackground: transparent });
    await page.close();
    return png;
  };

  const rounded = markSvg();
  const square = markSvg({ rounded: false });
  const maskable = markSvg({ rounded: false, scale: MARK.maskableScale });

  const files: [string, string, number, boolean][] = [
    ["favicon-32.png", rounded, 32, true],
    ["icon-192.png", rounded, 192, true],
    ["icon-512.png", rounded, 512, true],
    ["apple-touch-icon.png", square, 180, false],
    ["icon-maskable-512.png", maskable, 512, false],
  ];
  for (const [name, svg, px, transparent] of files) {
    writeFileSync(join(BRAND_DIR, name), await render(svg, px, transparent));
  }

  const ico = await Promise.all([16, 32, 48].map(async (size) => ({ size, data: await render(rounded, size, true) })));
  writeFileSync(join(ROOT, "src/app/favicon.ico"), packIco(ico));

  await browser.close();
  console.log("brand icons rebuilt");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
